"""
Script generator.
Orchestrates a conversation between AI hosts (and optional guests)
to produce a full podcast episode script.
"""

import json
import logging
from datetime import datetime
from pathlib import Path

from anthropic import Anthropic
from openai import OpenAI

import config
from pipeline.cost_tracker import tracker

logger = logging.getLogger(__name__)


def _load_prompt(name: str) -> str:
    """Load a prompt template from the prompts directory."""
    path = config.PROMPTS_DIR / name
    return path.read_text(encoding="utf-8")


def _build_episode_prompt(topics: list[dict], date: str, roster: list[str]) -> str:
    """Fill in the episode format template with today's topics and roster."""
    template = _load_prompt("episode_format.txt")
    duration = config.EPISODE_DURATION_MINUTES
    word_count = duration * 150  # ~150 words/min spoken
    min_word_count = int(word_count * 0.8)  # hard floor

    # Scale exchange counts based on target duration
    # These are calibrated so total output matches the word count target
    if duration >= 25:
        main_story_count = 3
        main_exchanges = 12       # deep dives, ~5-7 min each
        cold_open_exchanges = 3
        lightning_exchanges = 4
        signoff_exchanges = 4
    elif duration >= 15:
        main_story_count = 2
        main_exchanges = 8
        cold_open_exchanges = 2
        lightning_exchanges = 3
        signoff_exchanges = 3
    else:
        main_story_count = 2
        main_exchanges = 5
        cold_open_exchanges = 2
        lightning_exchanges = 2
        signoff_exchanges = 2

    # Build dynamic host description
    speaker_parts = []
    for name in roster:
        company = config.SPEAKERS[name]["company"]
        role = config.SPEAKERS[name]["role"]
        if role == "guest":
            speaker_parts.append(f"guest {name} ({company})")
        else:
            speaker_parts.append(f"{name} ({company})")

    if len(speaker_parts) == 2:
        hosts_description = f"hosted by {speaker_parts[0]} and {speaker_parts[1]}"
    else:
        hosts_description = (
            "hosted by "
            + ", ".join(speaker_parts[:-1])
            + f", and {speaker_parts[-1]}"
        )

    speaker_names = ", ".join(f'"{name}"' for name in roster)

    # Build optional guest segment text
    guests_in_roster = [n for n in roster if config.SPEAKERS[n]["role"] == "guest"]
    if guests_in_roster:
        guest_names = " and ".join(guests_in_roster)
        guest_segment = (
            f"3b. GUEST SPOTLIGHT — {guest_names} shares a unique perspective "
            f"on one main story. Hosts ask pointed questions. ({main_exchanges} exchanges)\n"
        )
    else:
        guest_segment = ""

    topics_text = "\n".join(
        f"- [{t.get('category', 'main').upper()}] {t['title']}: {t['summary']}"
        + (f" (Angle: {t['angle']})" if t.get("angle") else "")
        for t in topics
    )

    return template.format(
        date=date,
        topics=topics_text,
        duration=duration,
        word_count=word_count,
        min_word_count=min_word_count,
        hosts_description=hosts_description,
        speaker_names=speaker_names,
        guest_segment=guest_segment,
        main_story_count=main_story_count,
        main_exchanges=main_exchanges,
        cold_open_exchanges=cold_open_exchanges,
        lightning_exchanges=lightning_exchanges,
        signoff_exchanges=signoff_exchanges,
    )


def generate_script(topics: list[dict], roster: list[str] | None = None) -> dict:
    """
    Generate the full episode script.

    Strategy:
    1. Use Claude to draft the full script structure (it's good at nuance and format)
    2. Then run a "rewrite pass" where each speaker's lines are regenerated by their
       actual model, ensuring authentic voice.

    Returns the complete script as a dict with title, description, segments, and roster.
    """
    if roster is None:
        roster = config.get_episode_roster()

    date_str = datetime.now().strftime("%B %d, %Y")
    episode_prompt = _build_episode_prompt(topics, date_str, roster)

    logger.info("Step 1: Generating initial script structure...")
    raw_script = _generate_initial_script(episode_prompt, roster)

    logger.info("Step 2: Rewriting each host's lines through their own model...")
    final_script = _rewrite_with_authentic_voices(raw_script, topics, date_str, roster)

    logger.info("Step 3: Generating YouTube-optimized title...")
    final_script["youtube_title"] = _generate_youtube_title(final_script, topics)

    # Attach roster metadata for downstream consumers
    final_script["roster"] = roster

    return final_script


def _generate_initial_script(episode_prompt: str, roster: list[str]) -> dict:
    """Use Claude to generate the initial script structure."""
    client = Anthropic(api_key=config.ANTHROPIC_API_KEY)

    speaker_count = len(roster)
    system_msg = (
        "You are a podcast script writer. Generate a complete podcast script "
        "in the exact JSON format specified. Make it feel natural and conversational. "
        f"There are {speaker_count} speakers — each should have a distinct personality. "
        "Return ONLY valid JSON."
    )

    response = client.messages.create(
        model=config.CLAUDE_MODEL,
        max_tokens=16000,
        messages=[{"role": "user", "content": episode_prompt}],
        system=system_msg,
    )

    # Track usage
    tracker.record(
        step="initial_script",
        model=config.CLAUDE_MODEL,
        input_tokens=response.usage.input_tokens,
        output_tokens=response.usage.output_tokens,
        speaker="Claude",
    )

    text = response.content[0].text

    # Extract JSON from the response (handle markdown code blocks)
    if "```json" in text:
        text = text.split("```json")[1].split("```")[0]
    elif "```" in text:
        text = text.split("```")[1].split("```")[0]

    try:
        return json.loads(text.strip())
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse initial script: {e}")
        logger.debug(f"Raw response: {text[:500]}")
        raise


