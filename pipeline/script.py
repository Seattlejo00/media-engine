# Unified line rewriter
# ---------------------------------------------------------------------------

def _rewrite_line(
    client, speaker: str, persona: str, context: str, original: str, segment: dict
) -> str:
    """Rewrite a line through the speaker's own API for authentic voice."""
    speaker_config = config.SPEAKERS[speaker]
    api_type = speaker_config["api_type"]
    model = speaker_config["model"]
    segment_type = segment.get("type", "")
    topic = segment.get("topic", "")

    user_content = (
        f"You're in the '{segment_type}' segment of today's podcast"
        + (f" discussing: {topic}" if topic else "")
        + ".\n\n"
        + (f"Conversation so far:\n{context}\n\n" if context else "")
        + f'Your scripted line is: "{original}"\n\n'
        "Rewrite this in your authentic voice. Keep the same meaning "
        f"and information, but make it sound like YOU — {speaker} — actually "
        "talking. Keep it roughly the same length. Return ONLY the "
        "rewritten line, no quotes or attribution.\n\n"
        "IMPORTANT: Do NOT use filler phrases like 'honestly', 'if I'm being honest', "
        "'that's a great point', 'absolutely', 'let's dive in', 'at the end of the day', "
        "or 'it's worth noting'. Use varied, natural language."
    )

    if api_type == "anthropic":
        response = client.messages.create(
            model=model,
            max_tokens=500,
            system=persona,
            messages=[{"role": "user", "content": user_content}],
        )
        tracker.record(
            step="voice_rewrite", model=model, speaker=speaker,
            input_tokens=response.usage.input_tokens,
            output_tokens=response.usage.output_tokens,
        )
        return response.content[0].text.strip()

    elif api_type in ("openai", "xai"):
        response = client.chat.completions.create(
            model=model,
            max_tokens=500,
            messages=[
                {"role": "system", "content": persona},
                {"role": "user", "content": user_content},
            ],
        )
        usage = response.usage
        if usage:
            tracker.record(
                step="voice_rewrite", model=model, speaker=speaker,
                input_tokens=usage.prompt_tokens,
                output_tokens=usage.completion_tokens,
            )
        return response.choices[0].message.content.strip()

    elif api_type == "google":
        response = client.generate_content(f"{persona}\n\n{user_content}")
        # Gemini usage metadata
        meta = getattr(response, "usage_metadata", None)
        if meta:
            tracker.record(
                step="voice_rewrite", model=model, speaker=speaker,
                input_tokens=getattr(meta, "prompt_token_count", 0),
                output_tokens=getattr(meta, "candidates_token_count", 0),
            )
        return response.text.strip()

    return original  # fallback


def _rewrite_with_authentic_voices(
    script: dict, topics: list[dict], date_str: str, roster: list[str]
) -> dict:
    """
    Pass each speaker's lines through their actual model for authentic voice.
    Speakers without API keys keep their initial script text unchanged.
    """
    # Load persona prompts for all speakers in the roster
    personas = {}
    for speaker in roster:
        prompt_file = config.SPEAKERS[speaker]["persona_prompt"]
        try:
            personas[speaker] = _load_prompt(prompt_file)
        except FileNotFoundError:
            logger.warning(f"No persona prompt found for {speaker}: {prompt_file}")

    # Create API clients (skips speakers with missing keys)
    clients = _get_api_clients(roster)

    for segment in script.get("segments", []):
        dialogue = segment.get("dialogue", [])
        context_lines = []

        for line in dialogue:
            speaker = line["speaker"]
            original_text = line["text"]

            context = "\n".join(
                f"{l['speaker']}: {l['text']}" for l in context_lines
            )

            # Only rewrite if we have both a client and a persona for this speaker
            if speaker in clients and speaker in personas:
                try:
                    rewritten = _rewrite_line(
                        clients[speaker], speaker, personas[speaker],
                        context, original_text, segment,
                    )
                    line["text"] = rewritten
                except Exception as e:
                    logger.warning(f"Rewrite failed for {speaker}: {e}")

            context_lines.append({"speaker": speaker, "text": line["text"]})

    return script


def _generate_youtube_title(script: dict, topics: list[dict]) -> str:
    """Generate a click-worthy YouTube title from the episode content."""
    client = OpenAI(api_key=config.OPENAI_API_KEY)

    episode_title = script.get("title", "")
    main_topics = [t["title"] for t in topics if t.get("category") == "main"][:3]
    topics_str = "; ".join(main_topics) if main_topics else "AI news"

    resp = client.chat.completions.create(
        model="gpt-4o-mini",
        max_tokens=100,
        messages=[
            {
                "role": "system",
                "content": (
                    "You write YouTube video titles for an AI news podcast called "
                    "'The AI Daily' hosted by ChatGPT and Claude.\n\n"
                    "Rules for great YouTube titles:\n"
                    "- MAX 65 characters (hard limit — YouTube truncates longer ones)\n"
                    "- Lead with the most interesting/controversial topic\n"
                    "- Use a pattern like: 'Topic | The AI Daily' or 'Bold Claim — Topic | AI Daily'\n"
                    "- Create curiosity — make people NEED to click\n"
                    "- Avoid generic words like 'interesting', 'amazing', 'incredible'\n"
                    "- Don't use all caps or excessive punctuation\n"
                    "- Include 'AI Daily' for brand recognition\n\n"
                    "Return ONLY the title text, nothing else."
                ),
            },
            {
                "role": "user",
                "content": (
                    f"Episode script title: {episode_title}\n"
                    f"Main topics: {topics_str}\n\n"
                    "Write a click-worthy YouTube title."
                ),
            },
        ],
        temperature=0.9,
    )

    usage = resp.usage
    if usage:
        tracker.record(
            step="youtube_title", model="gpt-4o-mini",
            input_tokens=usage.prompt_tokens,
            output_tokens=usage.completion_tokens,
        )

    yt_title = resp.choices[0].message.content.strip().strip('"')
    logger.info(f"YouTube title: {yt_title}")
    return yt_title


def save_script(script: dict, output_dir: Path) -> Path:
    """Save the script to a JSON file."""
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / "script.json"
    path.write_text(json.dumps(script, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info(f"Script saved to {path}")
    return path
